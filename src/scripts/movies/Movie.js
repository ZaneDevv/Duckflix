export class Movie
{
    // --------------------------------------------------------------------------------
    // ATTRIBUTES
    // --------------------------------------------------------------------------------

    #image = "";
    #title = "";
    #year = "";

    // --------------------------------------------------------------------------------
    // CONSTRUCTORS
    // --------------------------------------------------------------------------------

    constructor(imageUrl, title, year)
    {
        this.#image = imageUrl;
        this.#title = title;
        this.#year = year;
    }

    // --------------------------------------------------------------------------------
    // GETTERS & SETTERS
    // --------------------------------------------------------------------------------

    get image()
    {
        return this.#image;
    }

    get title()
    {
        return this.#title;
    }

    get year()
    {
        return this.#year;
    }
}